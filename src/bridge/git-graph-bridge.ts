// Shared contract between the React interface and the desktop host.
export function createGitGraphBridge(transport: { invoke: (channel: string, ...args: any[]) => Promise<any>; on: (channel: string, listener: (...args: any[]) => void) => void; removeListener: (channel: string, listener: (...args: any[]) => void) => void }) {
  return {
  isPackaged: () => transport.invoke('app:is-packaged'),
  onRestored: callback => { const listener = () => callback(); transport.on('app:restored', listener); return () => transport.removeListener('app:restored', listener) },
  watch: path => transport.invoke('repo:watch', path),
  unwatch: () => transport.invoke('repo:unwatch'),
  onRepoChanged: callback => { const listener = (_event, path) => callback(path); transport.on('repo:changed', listener); return () => transport.removeListener('repo:changed', listener) },
  releaseInfo: () => transport.invoke('release:info'),
  releaseRun: (version, skipBump) => transport.invoke('release:run', version, skipBump),
  onReleaseLog: callback => { const listener = (_event, line) => callback(line); transport.on('release:log', listener); return () => transport.removeListener('release:log', listener) },
  onReleaseDone: callback => { const listener = (_event, result) => callback(result); transport.on('release:done', listener); return () => transport.removeListener('release:done', listener) },
  open: () => transport.invoke('repo:open'),
  fileAction: (path, file, action) => transport.invoke('repo:file-action', path, file, action),
  openFolder: path => transport.invoke('repo:open-folder', path),
  load: (path, showRemote, limit) => transport.invoke('repo:load', path, showRemote, limit),
  history: (path, showRemote, limit, skip, fingerprint) => transport.invoke('repo:history', path, showRemote, limit, skip, fingerprint),
  diff: (path, hash) => transport.invoke('repo:diff', path, hash),
  commitFiles: (path, hash) => transport.invoke('repo:commit-files', path, hash),
  browseFiles: (path, folder) => transport.invoke('repo:browse-files', path, folder),
  aiFiles: path => transport.invoke('repo:ai-files', path),
  documentationFiles: (path, includeFolders) => transport.invoke('repo:documentation-files', path, includeFolders),
  searchFiles: (path, query) => transport.invoke('repo:search-files', path, query),
  previewFile: (path, file) => transport.invoke('repo:preview-file', path, file),
  fileHistory: (path, file, rev) => transport.invoke('repo:file-history', path, file, rev),
  fileBlame: (path, file, rev) => transport.invoke('repo:file-blame', path, file, rev),
  conflictState: path => transport.invoke('repo:conflict-state', path),
  conflictRead: (path, file) => transport.invoke('repo:conflict-read', path, file),
  conflictSave: (path, file, original, content) => transport.invoke('repo:conflict-save', path, file, original, content),
  conflictAction: (path, operation, action) => transport.invoke('repo:conflict-action', path, operation, action),
  commitAction: (path, request) => transport.invoke('repo:commit-action', path, request),
  branches: path => transport.invoke('repo:branches', path),
  switchBranch: (path, ref) => transport.invoke('repo:switch-branch', path, ref),
  createBranch: (path, name) => transport.invoke('repo:create-branch', path, name),
  fetch: path => transport.invoke('repo:fetch', path),
  pull: path => transport.invoke('repo:pull', path),
  push: path => transport.invoke('repo:push', path),
  stage: (path, files) => transport.invoke('repo:stage', path, files),
  unstage: (path, files) => transport.invoke('repo:unstage', path, files),
  stagedDiff: path => transport.invoke('repo:staged-diff', path),
  workingDiff: (path, request) => transport.invoke('repo:working-diff', path, request),
  applyHunk: (path, request) => transport.invoke('repo:apply-hunk', path, request),
  lastMessage: path => transport.invoke('repo:last-message', path),
  commit: (path, message, options) => transport.invoke('repo:commit', path, message, options),
  commitAndPush: (path, message, options) => transport.invoke('repo:commit-push', path, message, options),
  discard: (path, files) => transport.invoke('repo:discard', path, files),
  discardHunk: (path, request) => transport.invoke('repo:discard-hunk', path, request),
  renameBranch: (path, name, newName) => transport.invoke('repo:rename-branch', path, name, newName),
  deleteBranch: (path, name, force) => transport.invoke('repo:delete-branch', path, name, force),
  deleteRemoteBranch: (path, ref) => transport.invoke('repo:delete-remote-branch', path, ref),
  setUpstream: (path, name, ref) => transport.invoke('repo:set-upstream', path, name, ref),
  branchOp: (path, type, ref) => transport.invoke('repo:branch-op', path, type, ref),
  checkoutRemote: (path, ref, name) => transport.invoke('repo:checkout-remote', path, ref, name),
  stashPush: (path, options) => transport.invoke('repo:stash-push', path, options),
  stashApply: (path, hash) => transport.invoke('repo:stash-apply', path, hash),
  stashPop: (path, hash) => transport.invoke('repo:stash-pop', path, hash),
  stashDrop: (path, hash) => transport.invoke('repo:stash-drop', path, hash),
  tags: path => transport.invoke('repo:tags', path),
  createTag: (path, request) => transport.invoke('repo:create-tag', path, request),
  deleteTag: (path, name, options) => transport.invoke('repo:delete-tag', path, name, options),
  pushTag: (path, name, remote) => transport.invoke('repo:push-tag', path, name, remote),
  forgeComment: (path, kind, id, body) => transport.invoke('repo:forge-comment', path, kind, id, body),
  forgeDetail: (path, kind, id) => transport.invoke('repo:forge-detail', path, kind, id),
  forgeInfo: path => transport.invoke('repo:forge-info', path),
  forgeFacets: (path, kind) => transport.invoke('repo:forge-facets', path, kind),
  forgeList: (path, kind, options) => transport.invoke('repo:forge-list', path, kind, options),
  hasIssueToken: path => transport.invoke('tokens:has', path),
  setIssueToken: (path, token) => transport.invoke('tokens:set', path, token),
  openIssue: url => transport.invoke('app:open-issue', url),
  generateCommitMessage: (path, id) => transport.invoke('repo:generate-message', path, id),
  cancelCommitMessage: id => transport.invoke('repo:cancel-message', id),
  improvements: {
    load: path => transport.invoke('improvements:load', path),
    save: (path, data) => transport.invoke('improvements:save', path, data),
  },
  agent: {
    send: (path, request) => transport.invoke('agent:send', path, request),
    cancel: id => transport.invoke('agent:cancel', id),
    load: path => transport.invoke('agent:load', path),
    save: (path, data) => transport.invoke('agent:save', path, data),
    onEvent: callback => { const listener = (_event, id, payload) => callback(id, payload); transport.on('agent:event', listener); return () => transport.removeListener('agent:event', listener) },
  },
  settings: { read: () => transport.invoke('settings:read'), set: (key, value) => transport.invoke('settings:set', key, value), revealFile: () => transport.invoke('settings:reveal-file'), readFile: () => transport.invoke('settings:read-file'), export: () => transport.invoke('settings:export'), import: () => transport.invoke('settings:import') },
  projects: {
    list: () => transport.invoke('projects:list'),
    status: paths => transport.invoke('projects:status', paths),
    setDefault: path => transport.invoke('projects:default', path),
    add: () => transport.invoke('projects:add'),
    open: (path, showRemote) => transport.invoke('projects:open', path, showRemote),
    select: path => transport.invoke('projects:select', path),
    worktree: (project, path, showRemote) => transport.invoke('projects:worktree', project, path, showRemote),
    remove: path => transport.invoke('projects:remove', path),
    createFolder: name => transport.invoke('folders:create', name),
    renameFolder: (id, name) => transport.invoke('folders:rename', id, name),
    reorderFolders: ids => transport.invoke('folders:reorder', ids),
    deleteFolder: id => transport.invoke('folders:delete', id),
    move: (path, folderId) => transport.invoke('projects:move', path, folderId),
    reorder: paths => transport.invoke('projects:reorder', paths),
    setCommand: (path, command) => transport.invoke('projects:command:set', path, command),
    setAppearance: (path, appearance) => transport.invoke('projects:appearance:set', path, appearance),
    runCommand: (path, worktree) => transport.invoke('projects:command:run', path, worktree),
  },
  }
}

