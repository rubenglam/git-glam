import { contextBridge, ipcRenderer } from 'electron'
contextBridge.exposeInMainWorld('gitGraph', {
  open: () => ipcRenderer.invoke('repo:open'),
  openFolder: path => ipcRenderer.invoke('repo:open-folder', path),
  load: (path, showRemote, limit) => ipcRenderer.invoke('repo:load', path, showRemote, limit),
  history: (path, showRemote, limit) => ipcRenderer.invoke('repo:history', path, showRemote, limit),
  diff: (path, hash) => ipcRenderer.invoke('repo:diff', path, hash),
  commitFiles: (path, hash) => ipcRenderer.invoke('repo:commit-files', path, hash),
  fileHistory: (path, file, rev) => ipcRenderer.invoke('repo:file-history', path, file, rev),
  fileBlame: (path, file, rev) => ipcRenderer.invoke('repo:file-blame', path, file, rev),
  commitAction: (path, request) => ipcRenderer.invoke('repo:commit-action', path, request),
  branches: path => ipcRenderer.invoke('repo:branches', path),
  switchBranch: (path, ref) => ipcRenderer.invoke('repo:switch-branch', path, ref),
  createBranch: (path, name) => ipcRenderer.invoke('repo:create-branch', path, name),
  fetch: path => ipcRenderer.invoke('repo:fetch', path),
  pull: path => ipcRenderer.invoke('repo:pull', path),
  push: path => ipcRenderer.invoke('repo:push', path),
  stage: (path, files) => ipcRenderer.invoke('repo:stage', path, files),
  unstage: (path, files) => ipcRenderer.invoke('repo:unstage', path, files),
  workingDiff: (path, request) => ipcRenderer.invoke('repo:working-diff', path, request),
  applyHunk: (path, request) => ipcRenderer.invoke('repo:apply-hunk', path, request),
  lastMessage: path => ipcRenderer.invoke('repo:last-message', path),
  commit: (path, message, options) => ipcRenderer.invoke('repo:commit', path, message, options),
  commitAndPush: (path, message, options) => ipcRenderer.invoke('repo:commit-push', path, message, options),
  discard: (path, files) => ipcRenderer.invoke('repo:discard', path, files),
  discardHunk: (path, request) => ipcRenderer.invoke('repo:discard-hunk', path, request),
  renameBranch: (path, name, newName) => ipcRenderer.invoke('repo:rename-branch', path, name, newName),
  deleteBranch: (path, name, force) => ipcRenderer.invoke('repo:delete-branch', path, name, force),
  deleteRemoteBranch: (path, ref) => ipcRenderer.invoke('repo:delete-remote-branch', path, ref),
  setUpstream: (path, name, ref) => ipcRenderer.invoke('repo:set-upstream', path, name, ref),
  branchOp: (path, type, ref) => ipcRenderer.invoke('repo:branch-op', path, type, ref),
  checkoutRemote: (path, ref, name) => ipcRenderer.invoke('repo:checkout-remote', path, ref, name),
  stashPush: (path, options) => ipcRenderer.invoke('repo:stash-push', path, options),
  stashApply: (path, hash) => ipcRenderer.invoke('repo:stash-apply', path, hash),
  stashPop: (path, hash) => ipcRenderer.invoke('repo:stash-pop', path, hash),
  stashDrop: (path, hash) => ipcRenderer.invoke('repo:stash-drop', path, hash),
  tags: path => ipcRenderer.invoke('repo:tags', path),
  createTag: (path, request) => ipcRenderer.invoke('repo:create-tag', path, request),
  deleteTag: (path, name, options) => ipcRenderer.invoke('repo:delete-tag', path, name, options),
  pushTag: (path, name, remote) => ipcRenderer.invoke('repo:push-tag', path, name, remote),
  forgeComment: (path, kind, id, body) => ipcRenderer.invoke('repo:forge-comment', path, kind, id, body),
  forgeDetail: (path, kind, id) => ipcRenderer.invoke('repo:forge-detail', path, kind, id),
  forgeInfo: path => ipcRenderer.invoke('repo:forge-info', path),
  forgeFacets: (path, kind) => ipcRenderer.invoke('repo:forge-facets', path, kind),
  forgeList: (path, kind, options) => ipcRenderer.invoke('repo:forge-list', path, kind, options),
  hasIssueToken: path => ipcRenderer.invoke('tokens:has', path),
  setIssueToken: (path, token) => ipcRenderer.invoke('tokens:set', path, token),
  openIssue: url => ipcRenderer.invoke('app:open-issue', url),
  generateCommitMessage: (path, id) => ipcRenderer.invoke('repo:generate-message', path, id),
  cancelCommitMessage: id => ipcRenderer.invoke('repo:cancel-message', id),
  agent: {
    send: (path, request) => ipcRenderer.invoke('agent:send', path, request),
    cancel: id => ipcRenderer.invoke('agent:cancel', id),
    load: path => ipcRenderer.invoke('agent:load', path),
    save: (path, data) => ipcRenderer.invoke('agent:save', path, data),
    onEvent: callback => { const listener = (_event, id, payload) => callback(id, payload); ipcRenderer.on('agent:event', listener); return () => ipcRenderer.removeListener('agent:event', listener) },
  },
  settings: { read: () => ipcRenderer.invoke('settings:read'), set: (key, value) => ipcRenderer.invoke('settings:set', key, value) },
  projects: {
    list: () => ipcRenderer.invoke('projects:list'),
    status: paths => ipcRenderer.invoke('projects:status', paths),
    setDefault: path => ipcRenderer.invoke('projects:default', path),
    add: () => ipcRenderer.invoke('projects:add'),
    open: (path, showRemote) => ipcRenderer.invoke('projects:open', path, showRemote),
    select: path => ipcRenderer.invoke('projects:select', path),
    worktree: (project, path, showRemote) => ipcRenderer.invoke('projects:worktree', project, path, showRemote),
    remove: path => ipcRenderer.invoke('projects:remove', path),
    createFolder: name => ipcRenderer.invoke('folders:create', name),
    renameFolder: (id, name) => ipcRenderer.invoke('folders:rename', id, name),
    reorderFolders: ids => ipcRenderer.invoke('folders:reorder', ids),
    deleteFolder: id => ipcRenderer.invoke('folders:delete', id),
    move: (path, folderId) => ipcRenderer.invoke('projects:move', path, folderId),
    reorder: paths => ipcRenderer.invoke('projects:reorder', paths),
    setCommand: (path, command) => ipcRenderer.invoke('projects:command:set', path, command),
    setAppearance: (path, appearance) => ipcRenderer.invoke('projects:appearance:set', path, appearance),
    runCommand: (path, worktree) => ipcRenderer.invoke('projects:command:run', path, worktree),
  },
})
